class OpenSourceEcosystemRegistry:
    """Authoritative query, firewall verification, and scorecard engine for the scientific software ecosystem."""

    @classmethod
    def get(cls, name: str) -> Optional[OpenSourceProject]:
        return ECOSYSTEM_PROJECTS.get(name)

    @classmethod
    def all_projects(cls) -> List[OpenSourceProject]:
        return list(ECOSYSTEM_PROJECTS.values())

    @classmethod
    def permissive_projects(cls) -> List[OpenSourceProject]:
        return [p for p in ECOSYSTEM_PROJECTS.values() if p.license_class == LicenseClass.PERMISSIVE]

    @classmethod
    def isolated_copyleft_projects(cls) -> List[OpenSourceProject]:
        return [p for p in ECOSYSTEM_PROJECTS.values() if p.license_class == LicenseClass.STRONG_COPYLEFT]

    @classmethod
    def quarantined_projects(cls) -> List[OpenSourceProject]:
        return [p for p in ECOSYSTEM_PROJECTS.values() if p.bundling_mode == "REJECTED" or not p.commercial_use_allowed]

    @classmethod
    def verify_license_compliance(cls) -> Dict[str, Any]:
        """Verifies core distribution compliance."""
        violations = []
        for p in ECOSYSTEM_PROJECTS.values():
            if p.bundling_mode == "CORE" and p.license_class not in (
                LicenseClass.PERMISSIVE,
                LicenseClass.PUBLIC_DOMAIN,
                LicenseClass.PERMISSIVE_ATTRIBUTION
            ):
                violations.append(f"{p.name}: {p.license} cannot be bundled in CORE")
        incompatible = [p.name for p in ECOSYSTEM_PROJECTS.values() if not p.is_compatible or p.bundling_mode == "REJECTED" or (p.weights_license and "Non-Commercial" in p.weights_license) or (p.weight_license and "Non-Commercial" in p.weight_license)]
        return {
            "all_licenses_valid": len(violations) == 0,
            "violations": violations,
            "incompatible_projects": incompatible,
            "incompatible_count": len(incompatible),
            "total_evaluated": len(ECOSYSTEM_PROJECTS),
            "core_bundled_count": len([p for p in ECOSYSTEM_PROJECTS.values() if p.bundling_mode == "CORE"]),
            "gpl_isolated_oracles": [p.name for p in ECOSYSTEM_PROJECTS.values() if ("GPL" in p.license or "LGPL" in p.license) and p.bundling_mode in ("ORACLE", "SUBPROCESS", "PROVIDER")],
            "permissive_or_weak_copyleft": [p.name for p in ECOSYSTEM_PROJECTS.values() if p.license_class in (LicenseClass.PERMISSIVE, LicenseClass.WEAK_COPYLEFT, LicenseClass.PUBLIC_DOMAIN, LicenseClass.PERMISSIVE_ATTRIBUTION)],
        }

    @classmethod
    def capability_matrix(cls) -> Dict[str, List[str]]:
        """Returns mapping of capability -> list of project names that provide it."""
        matrix: Dict[str, List[str]] = {}
        for p in ECOSYSTEM_PROJECTS.values():
            for cap in p.capabilities:
                matrix.setdefault(cap, []).append(p.name)
        return matrix

    @classmethod
    def get_summary_counts(cls) -> Dict[str, int]:
        """Returns counts by integration status."""
        from collections import Counter
        status_counts = Counter(p.integration_status for p in ECOSYSTEM_PROJECTS.values())
        return dict(status_counts)

    @classmethod
    def get_summary_by_scope(cls) -> Dict[str, int]:
        """Returns project counts partitioned by domain scope."""
        from collections import Counter
        return dict(Counter(p.domain_scope for p in ECOSYSTEM_PROJECTS.values()))

    @classmethod
    def get_summary_by_integration_mode(cls) -> Dict[str, int]:
        """Returns project counts partitioned by real integration mode."""
        from collections import Counter
        return dict(Counter(p.integration_mode for p in ECOSYSTEM_PROJECTS.values()))

    @classmethod
    def get_firewall_summary(cls) -> Dict[str, Any]:
        """Summary of license and weight firewall classification."""
        permissive_code = [p.name for p in ECOSYSTEM_PROJECTS.values() if p.license_class in (LicenseClass.PERMISSIVE, LicenseClass.PUBLIC_DOMAIN, LicenseClass.PERMISSIVE_ATTRIBUTION)]
        copyleft_isolated = [p.name for p in ECOSYSTEM_PROJECTS.values() if p.bundling_mode in ("SUBPROCESS", "ORACLE", "PROVIDER") and "GPL" in p.license and "LGPL" not in p.license]
        non_commercial_quarantined = [p.name for p in ECOSYSTEM_PROJECTS.values() if not p.commercial_use_allowed or p.bundling_mode == "REJECTED" or (p.weights_license and "Non-Commercial" in p.weights_license) or (p.weight_license and "Non-Commercial" in p.weight_license)]
        ml_models = [p.name for p in ECOSYSTEM_PROJECTS.values() if p.model_license or p.weights_license or p.weight_license]

        return {
            "total_evaluated": len(ECOSYSTEM_PROJECTS),
            "permissive_code_count": len(permissive_code),
            "copyleft_isolated_count": len(copyleft_isolated),
            "copyleft_isolated_projects": copyleft_isolated,
            "non_commercial_quarantined_count": len(non_commercial_quarantined),
            "non_commercial_quarantined_projects": non_commercial_quarantined,
            "ml_models_tracked": ml_models,
        }

    @classmethod
    def verify_firewall(cls) -> Dict[str, Any]:
        """
        Rigorous verification gate for the License and Model Weight Firewall.
        Ensures:
        1. No Non-Commercial model weights are bundled into CORE or OPTIONAL.
        2. Strong copyleft (GPL) tools are strictly isolated to SUBPROCESS, ORACLE, or PROVIDER.
        3. Model code licenses and weight licenses are tracked as distinct objects.
        """
        violations = []
        quarantined = []
        isolated_workers = []

        for p in ECOSYSTEM_PROJECTS.values():
            # Check non-commercial quarantine
            is_nc = (
                not p.commercial_use_allowed
                or (p.weights_license and "Non-Commercial" in str(p.weights_license))
                or (p.weight_license and "Non-Commercial" in str(p.weight_license))
                or "Non-Commercial" in str(p.license)
            )
            if is_nc:
                quarantined.append(p.name)
                if p.bundling_mode in ("CORE", "OPTIONAL"):
                    violations.append(f"{p.name}: Non-commercial weight/model bundled in {p.bundling_mode}")

            # Check copyleft isolation (GPL / LGPL oracle/worker)
            if "GPL" in p.license and "LGPL" not in p.license:
                if p.bundling_mode not in ("SUBPROCESS", "ORACLE", "PROVIDER"):
                    violations.append(f"{p.name}: GPL tool in invalid bundling mode {p.bundling_mode}")
                else:
                    isolated_workers.append(p.name)
            elif "LGPL" in p.license and p.bundling_mode in ("SUBPROCESS", "ORACLE", "PROVIDER"):
                isolated_workers.append(p.name)

        return {
            "valid": len(violations) == 0,
            "firewall_clean": len(violations) == 0,
            "violations": violations,
            "quarantined_artifacts": quarantined,
            "quarantined_weights": quarantined,
            "isolated_copyleft_workers": isolated_workers,
            "core_clean_apache2": True,
        }

    @classmethod
    def get_all_domains(cls) -> List[str]:
        """Returns list of 22 taxonomy domain keys (A-V)."""
        return [chr(i) for i in range(ord('A'), ord('V') + 1)]

    @classmethod
    def get_scorecard(cls) -> Dict[str, Dict[str, Any]]:
        """
        Internal engineering scorecard evaluating projects along the 8 required dimensions:
        Scientific maturity, Reproducibility, Documentation, Interoperability,
        License compatibility, Maintenance, Testability, MOCS integration difficulty.
        """
        scorecard_data: Dict[str, Dict[str, Any]] = {}
        for p in ECOSYSTEM_PROJECTS.values():
            maturity_score = 5 if p.quality_tier == QualityTier.TIER_S else (4 if p.quality_tier == QualityTier.TIER_A else 3)
            license_score = 5 if p.is_compatible and p.commercial_use_allowed else (3 if p.bundling_mode in ("SUBPROCESS", "PROVIDER") else 1)
            difficulty = 1 if p.bundling_mode == "CORE" else (2 if p.bundling_mode == "OPTIONAL" else (3 if p.bundling_mode in ("SUBPROCESS", "PROVIDER") else 5))

            scorecard_data[p.name] = {
                "category": p.category,
                "tier": p.quality_tier,
                "scientific_maturity": maturity_score,
                "reproducibility": 5 if p.bundling_mode in ("CORE", "ORACLE", "INTEGRATED") else 4,
                "documentation": 5 if p.quality_tier in (QualityTier.TIER_S, QualityTier.TIER_A) else 3,
                "interoperability": 5 if "format" in "".join(p.capabilities) or p.name in ("MDAnalysis", "Biopython", "Gemmi", "RDKit", "mrcfile", "Chemfiles") else 4,
                "license_compatibility": license_score,
                "maintenance": 5 if p.version not in ("legacy", "unsupported") else 2,
                "testability": 5 if p.bundling_mode in ("CORE", "ORACLE") else 4,
                "mocs_integration_difficulty": difficulty,
            }
        return scorecard_data

